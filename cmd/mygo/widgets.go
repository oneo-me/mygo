// Widgets (package widget) need a widget extension in the app's bundle,
// which WidgetKit runs to draw them: mygo build and mygo dev compile one
// with Xcode's swiftc from widgets/Widgets.swift, which draws the
// timelines the app writes with SwiftUI, and Kinds.swift, which declares
// the kinds of mygo.json. Beside it in the bundle's frameworks goes a
// library of widgets/Reload.swift, through which package widget asks
// WidgetKit to reload them. The Info.plist of both says where the
// timelines are: in the container of an app group they share
// (appGroupKey), which their entitlements grant, as on iOS, or on macOS
// by default in a directory of the user's home (widgetsPathKey), which
// the app writes and the extension, in the App Sandbox, may read: macOS
// lets no app signed ad hoc, as by mygo dev, into a group's container.

//go:embed widgets/Widgets.swift widgets/Reload.swift
var widgetSources embed.FS

const (
	widgetsAppex = "Widgets.appex"
	widgetsExec  = "Widgets"
	widgetKit    = "MyGoWidgetKit"
	// widgetKitDylib is the reload library on macOS, a plain library
	// among the frameworks; iOS's is a framework, as the App Store takes
	// no other.
	widgetKitDylib = "libMyGoWidgetKit.dylib"
	appGroupKey    = "MyGoAppGroup"
	widgetsPathKey = "MyGoWidgetsPath"
	// maxWidgets is how many kinds a WidgetBundle holds.
	maxWidgets = 10
)

var (
	widgetKindRe   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$`)
	widgetFamilies = []string{"small", "medium", "large", "extraLarge", "circular", "rectangular", "inline"}
	appGroupRe     = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9.-]*$`)
)

func (c *Config) validateWidgets() error {
	if len(c.Widgets) > maxWidgets {
		return fmt.Errorf("widgets lists %d kinds, more than the %d a widget extension holds", len(c.Widgets), maxWidgets)
	}
	seen := map[string]bool{}
	for i, w := range c.Widgets {
		if !widgetKindRe.MatchString(w.Kind) {
			return fmt.Errorf("widgets[%d].kind %q is not a kind: letters, digits, '.', '_' and '-', up to 64", i, w.Kind)
		}
		if seen[w.Kind] {
			return fmt.Errorf("widgets[%d]: the kind %q is listed twice", i, w.Kind)
		}
		seen[w.Kind] = true
		for _, f := range w.Families {
			if !slices.Contains(widgetFamilies, f) {
				return fmt.Errorf("widgets[%d].families: %q is none of %s", i, f, strings.Join(widgetFamilies, ", "))
			}
		}
	}
	for key, g := range map[string]string{"macos.appGroup": c.MacOS.AppGroup, "ios.appGroup": c.IOS.AppGroup} {
		if g != "" && !appGroupRe.MatchString(g) {
			return fmt.Errorf("%s %q is not an app group, as group.com.example.app", key, g)
		}
	}
	return nil
}

func (w Widget) name() string {
	if w.Name == "" {
		return w.Kind
	}
	return w.Name
}

func (w Widget) families() []string {
	if len(w.Families) == 0 {
		return []string{"small", "medium", "large"}
	}
	return w.Families
}

// iosAppGroup is the app group of the iOS app and its widgets.
func (c *Config) iosAppGroup() string {
	if c.IOS.AppGroup != "" {
		return c.IOS.AppGroup
	}
	return "group." + c.Identifier
}

// macWidgetsPath is where the macOS app keeps what its widgets show
// without an app group, from the user's home.
func (c *Config) macWidgetsPath() string {
	return filepath.Join("Library", "Application Support", c.Identifier, "Widgets")
}

// macWidgetsStore returns the keys of the Info.plists of the macOS app and
// its widget extension that say where the timelines are.
func (c *Config) macWidgetsStore() map[string]any {
	if c.MacOS.AppGroup != "" {
		return map[string]any{appGroupKey: c.MacOS.AppGroup}
	}
	return map[string]any{widgetsPathKey: c.macWidgetsPath()}
}

// checkMacSandbox reports an app in the App Sandbox without an app group,
// which could write no timeline where its widgets read them.
func checkMacSandbox(c *Config) error {
	if c.MacOS.AppGroup != "" || c.MacOS.Entitlements == "" {
		return nil
	}
	d, err := readPlist(c.path(c.MacOS.Entitlements))
	if err != nil {
		return err
	}
	if d["com.apple.security.app-sandbox"] == true {
		return errors.New("macos.entitlements put the app in the App Sandbox: set macos.appGroup, the app group through which it shares what its widgets show")
	}
	return nil
}

// kindsSwift returns Kinds.swift, the declaration of the kinds of widgets.
func kindsSwift(c *Config) string {
	var b strings.Builder
	b.WriteString("// Code generated by mygo from the widgets of " + c.configName() + ". DO NOT EDIT.\n\nimport SwiftUI\nimport WidgetKit\n")
	for i, w := range c.Widgets {
		var fams []string
		for _, f := range w.families() {
			fams = append(fams, swiftString(f))
		}
		fmt.Fprintf(&b, `
struct MyGoWidget%d: Widget {
    var body: some WidgetConfiguration {
        StaticConfiguration(kind: %s, provider: MyGoProvider(kind: %[2]s)) { entry in
            MyGoEntryView(entry: entry, name: %[3]s, description: %[4]s)
        }
        .configurationDisplayName(Text(verbatim: %[3]s))
        .description(Text(verbatim: %[4]s))
        .supportedFamilies(families([%[5]s]))
    }
}
`, i, swiftString(w.Kind), swiftString(w.name()), swiftString(w.Description), strings.Join(fams, ", "))
	}
	b.WriteString("\n@main\nstruct MyGoWidgets: WidgetBundle {\n    var body: some Widget {\n")
	for i := range c.Widgets {
		fmt.Fprintf(&b, "        MyGoWidget%d()\n", i)
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

// swiftString quotes s as a Swift string literal.
func swiftString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"', '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// widgetTarget is what the widget extension is compiled for: an SDK and
// the targets of swiftc, two for a universal macOS app.
type widgetTarget struct {
	sdk     string
	triples []string
	ios     bool
}

// atLeast returns version, or floor when version is older.
func atLeast(version, floor string) string {
	parse := func(v string) []int {
		var out []int
		for _, p := range strings.Split(v, ".") {
			n, _ := strconv.Atoi(p)
			out = append(out, n)
		}
		return out
	}
	v, f := parse(version), parse(floor)
	for len(v) < len(f) {
		v = append(v, 0)
	}
	for len(f) < len(v) {
		f = append(f, 0)
	}
	if slices.Compare(v, f) < 0 {
		return floor
	}
	return version
}

// macWidgetTarget compiles for macOS 11, which WidgetKit needs, or later.
func macWidgetTarget(c *Config, goarch string) widgetTarget {
	min := atLeast(c.MacOS.MinimumSystemVersion, "11.0")
	t := widgetTarget{sdk: "macosx"}
	archs := []string{goarch}
	if goarch == "universal" {
		archs = []string{"arm64", "amd64"}
	}
	for _, a := range archs {
		if a == "amd64" {
			a = "x86_64"
		}
		t.triples = append(t.triples, a+"-apple-macos"+min)
	}
	return t
}

// iosWidgetTarget compiles for iOS 14, which WidgetKit needs, or later.
func iosWidgetTarget(c *Config, it iosTarget) widgetTarget {
	arch := it.arch
	if arch == "amd64" {
		arch = "x86_64"
	}
	triple := arch + "-apple-ios" + atLeast(c.IOS.MinimumOSVersion, "14.0")
	if it.simulator {
		triple += "-simulator"
	}
	return widgetTarget{sdk: it.sdk(), triples: []string{triple}, ios: true}
}

// compileWidgets compiles the widget extension's executable and the
// reload library for t, and returns their paths. They are kept in the
// user's cache, by their sources, the target and the toolchain, so that
// builds compile them once.
func compileWidgets(c *Config, t widgetTarget) (exe, lib string, err error) {
	if runtime.GOOS != "darwin" {
		return "", "", errors.New("widgets need a Mac with Xcode, whose swiftc compiles their extension")
	}
	widgetsSwift, _ := widgetSources.ReadFile("widgets/Widgets.swift")
	reloadSwift, _ := widgetSources.ReadFile("widgets/Reload.swift")
	kinds := kindsSwift(c)
	version, err := exec.Command("xcrun", "--sdk", t.sdk, "swiftc", "--version").CombinedOutput()
	if err != nil {
		return "", "", fmt.Errorf("cannot find Xcode's swiftc for the %s SDK, which compiles the widgets: %v\n%s", t.sdk, err, version)
	}
	sdk, _ := exec.Command("xcrun", "--sdk", t.sdk, "--show-sdk-path").Output()
	h := sha256.New()
	for _, part := range [][]byte{widgetsSwift, reloadSwift, []byte(kinds), version, sdk, []byte(t.sdk + " " + strings.Join(t.triples, " "))} {
		fmt.Fprintf(h, "%d:", len(part))
		h.Write(part)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		return "", "", err
	}
	dir := filepath.Join(cache, "mygo", "widgets", hex.EncodeToString(h.Sum(nil))[:24])
	exe, lib = filepath.Join(dir, widgetsExec), filepath.Join(dir, widgetKit)
	if fileExists(exe) && fileExists(lib) {
		return exe, lib, nil
	}

	if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
		return "", "", err
	}
	work, err := os.MkdirTemp(filepath.Dir(dir), ".build-")
	if err != nil {
		return "", "", err
	}
	defer os.RemoveAll(work)
	for name, src := range map[string][]byte{"Widgets.swift": widgetsSwift, "Kinds.swift": []byte(kinds), "Reload.swift": reloadSwift} {
		if err := os.WriteFile(filepath.Join(work, name), src, 0o644); err != nil {
			return "", "", err
		}
	}
	installName := "@rpath/" + widgetKitDylib
	if t.ios {
		installName = "@rpath/" + widgetKit + ".framework/" + widgetKit
	}
	swiftc := func(triple, out string, args ...string) error {
		args = append([]string{"--sdk", t.sdk, "swiftc", "-target", triple, "-O", "-swift-version", "5",
			"-parse-as-library", "-application-extension", "-o", out}, args...)
		cmd := exec.Command("xcrun", args...)
		cmd.Dir = work
		if msg, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("swiftc -target %s: %v\n%s", triple, err, bytes.TrimSpace(msg))
		}
		return nil
	}
	var exes, libs []string
	for _, triple := range t.triples {
		e, l := filepath.Join(work, widgetsExec+"-"+triple), filepath.Join(work, widgetKit+"-"+triple)
		// App extensions start in NSExtensionMain, as Xcode links them,
		// which runs the WidgetBundle of @main.
		if err := swiftc(triple, e, "-module-name", "MyGoWidgets", "-Xlinker", "-e", "-Xlinker", "_NSExtensionMain",
			"-Xlinker", "-dead_strip", "Widgets.swift", "Kinds.swift"); err != nil {
			return "", "", err
		}
		if err := swiftc(triple, l, "-emit-library", "-module-name", widgetKit, "-Xlinker", "-install_name", "-Xlinker", installName,
			"Reload.swift"); err != nil {
			return "", "", err
		}
		exes, libs = append(exes, e), append(libs, l)
	}
	out := filepath.Join(work, "out")
	if err := os.Mkdir(out, 0o755); err != nil {
		return "", "", err
	}
	for _, f := range []struct {
		dst    string
		slices []string
	}{{filepath.Join(out, widgetsExec), exes}, {filepath.Join(out, widgetKit), libs}} {
		if len(f.slices) == 1 {
			err = os.Rename(f.slices[0], f.dst)
		} else {
			err = writeUniversal(f.dst, f.slices...)
		}
		if err != nil {
			return "", "", err
		}
	}
	if err := os.Rename(out, dir); err != nil && !fileExists(exe) {
		return "", "", err
	}
	return exe, lib, nil
}

// plistBytes returns a property list of d.
func plistBytes(d map[string]any) []byte {
	var b bytes.Buffer
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
`)
	writePlistValue(&b, d, "")
	b.WriteString("</plist>\n")
	return b.Bytes()
}

// widgetsInfo returns the keys of the widget extension's Info.plist that
// macOS and iOS share, with those of store.
func widgetsInfo(c *Config, store map[string]any) map[string]any {
	d := map[string]any{
		"CFBundleName":                  c.Name,
		"CFBundleDisplayName":           c.Name,
		"CFBundleIdentifier":            c.Identifier + ".widgets",
		"CFBundleVersion":               c.Version,
		"CFBundleShortVersionString":    c.Version,
		"CFBundleExecutable":            widgetsExec,
		"CFBundlePackageType":           "XPC!",
		"CFBundleInfoDictionaryVersion": "6.0",
		"NSExtension":                   map[string]any{"NSExtensionPointIdentifier": "com.apple.widgetkit-extension"},
	}
	for k, v := range store {
		d[k] = v
	}
	if langs, _ := c.languages(); len(langs) > 0 {
		d["CFBundleDevelopmentRegion"] = lprojName(langs[0].Tag)
	}
	if c.Copyright != "" {
		d["NSHumanReadableCopyright"] = c.Copyright
	}
	return d
}

// addMacWidgets puts the widget extension and the reload library into a
// macOS bundle built for goarch.
func addMacWidgets(c *Config, app, goarch string) error {
	if err := checkMacSandbox(c); err != nil {
		return err
	}
	exe, lib, err := compileWidgets(c, macWidgetTarget(c, goarch))
	if err != nil {
		return err
	}
	contents := filepath.Join(app, "Contents", "PlugIns", widgetsAppex, "Contents")
	if err := os.MkdirAll(filepath.Join(contents, "MacOS"), 0o755); err != nil {
		return err
	}
	if err := copyFile(exe, filepath.Join(contents, "MacOS", widgetsExec), 0o755); err != nil {
		return err
	}
	info := widgetsInfo(c, c.macWidgetsStore())
	info["CFBundleSupportedPlatforms"] = []any{"MacOSX"}
	info["LSMinimumSystemVersion"] = atLeast(c.MacOS.MinimumSystemVersion, "11.0")
	if err := os.WriteFile(filepath.Join(contents, "Info.plist"), plistBytes(info), 0o644); err != nil {
		return err
	}
	if p := c.MacOS.WidgetsProvisioningProfile; p != "" {
		if err := copyFile(c.path(p), filepath.Join(contents, "embedded.provisionprofile"), 0o644); err != nil {
			return fmt.Errorf("macos.widgetsProvisioningProfile %s: %w", p, err)
		}
	}
	frameworks := filepath.Join(app, "Contents", "Frameworks")
	if err := os.MkdirAll(frameworks, 0o755); err != nil {
		return err
	}
	return copyFile(lib, filepath.Join(frameworks, widgetKitDylib), 0o755)
}

// addIOSWidgets puts the widget extension and the reload framework into
// an iOS bundle built for t.
func addIOSWidgets(c *Config, app string, t iosTarget) error {
	exe, lib, err := compileWidgets(c, iosWidgetTarget(c, t))
	if err != nil {
		return err
	}
	platform := "iPhoneOS"
	if t.simulator {
		platform = "iPhoneSimulator"
	}
	appex := filepath.Join(app, "PlugIns", widgetsAppex)
	if err := os.MkdirAll(appex, 0o755); err != nil {
		return err
	}
	if err := copyFile(exe, filepath.Join(appex, widgetsExec), 0o755); err != nil {
		return err
	}
	info := widgetsInfo(c, map[string]any{appGroupKey: c.iosAppGroup()})
	info["CFBundleSupportedPlatforms"] = []any{platform}
	info["DTPlatformName"] = t.sdk()
	info["MinimumOSVersion"] = atLeast(c.IOS.MinimumOSVersion, "14.0")
	info["UIDeviceFamily"] = []any{1.0, 2.0}
	if err := os.WriteFile(filepath.Join(appex, "Info.plist"), plistBytes(info), 0o644); err != nil {
		return err
	}
	fw := filepath.Join(app, "Frameworks", widgetKit+".framework")
	if err := os.MkdirAll(fw, 0o755); err != nil {
		return err
	}
	if err := copyFile(lib, filepath.Join(fw, widgetKit), 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(fw, "Info.plist"), plistBytes(map[string]any{
		"CFBundleIdentifier":            c.Identifier + ".widgetkit",
		"CFBundleExecutable":            widgetKit,
		"CFBundleName":                  widgetKit,
		"CFBundlePackageType":           "FMWK",
		"CFBundleVersion":               c.Version,
		"CFBundleShortVersionString":    c.Version,
		"CFBundleInfoDictionaryVersion": "6.0",
		"CFBundleSupportedPlatforms":    []any{platform},
		"DTPlatformName":                t.sdk(),
		"MinimumOSVersion":              atLeast(c.IOS.MinimumOSVersion, "14.0"),
	}), 0o644)
}

